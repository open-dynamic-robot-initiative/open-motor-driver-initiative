/**
 * @brief           Reset the ENCODER structure
 * @param[inout]    *p_enc   Pointer on the ENCODER structure to reset.
 */
inline void ENC_resetStruct(ENC_STRUCT* p_enc)
{
    SPEED_STRUCT* p_speed   = &p_enc->speedEst;

    p_enc->thetaMech[NEW]   = 0.0;
    p_enc->thetaMech[OLD]   = 0.0;
    p_enc->thetaElec        = 0.0;
    p_enc->thetaDir         = false;
//    p_enc->thetaNew             = false;

    p_enc->indexCompensated = false;
    p_enc->indexTheta       = 0.0f;
    p_enc->indexedThetaMech = 0.0f;

    p_enc->thetaAbsolute    = 0.0f;

    p_speed->alpha          = 0.0f;
    p_speed->speedRef       = 0.0f;
    p_speed->theta[NEW]     = 0.0f;
    p_speed->theta[OLD]     = 0.0f;
    p_speed->speedLow       = 0.0f;
    p_speed->speedHigh      = 0.0f;
    p_speed->speedMech      = 0.0f;
    p_speed->speedElec      = 0.0f;

    p_enc->turnNb           = 0;
    p_enc->indexDetected    = false;
    p_enc->indexToggle      = false;
    p_enc->rollOverFlag     = false;
}

/**
 * @brief           Reset ENCODER structure and set EQEP position counter to a defined position (alignment routine)
 * @param[inout]    *p_enc   Pointer on the ENCODER structure to reset.
 */
inline void ENC_setPosition(ENC_STRUCT* p_enc, uint32_t pos)
{
    // Reset encoder position
    EQEP_setPosition(p_enc->p_qepHandle->eqepBase, pos);
    // Reset encoder structure
    ENC_resetStruct(p_enc);
}

/**
 * @brief           Read the position latched on ADCSOC event (generated by PWM SOC), direction \& electric position
 * @param[inout]    *p_enc   Pointer on the ENCODER structure.
 */
inline void ENC_getPosition(ENC_STRUCT* p_enc)
{
    p_enc->thetaMech[OLD]   = p_enc->thetaMech[NEW];
    // Compute mechanical angle normalized between 0 and 1
    p_enc->thetaMech[NEW]   = (float32_t)(p_enc->p_qepRegs->QPOSSLAT) / p_enc->thetaMechScaler;
    //p_enc->thetaMech    = (float32_t)(*p_enc->p_qepCntPosReg) / p_enc->mechScaler;
    // Get direction : 0 = CCW/reverse, 1 = CW/forward
    p_enc->thetaDir         = p_enc->p_qepRegs->QEPSTS.bit.QDF;
    // Compute electrical angle (each pole pair is normalized between 0 and 1)
    p_enc->thetaElec        = __fracf32(p_enc->polePairs * p_enc->thetaMech[NEW]);
}

// Encoder update routine, this is not critical for the control loop to be executed
// so it is executed after the control loop.
// Reference manual par 27.6 contains all the information
// necessary to understand this routine
inline void ENC_getSpeed(ENC_STRUCT* p_enc)
{
    volatile struct EQEP_REGS*  p_qepRegs   = p_enc->p_qepRegs;
    SPEED_STRUCT*               p_speed     = &p_enc->speedEst;
    float32_t                   deltaTheta  = 0.0;

    //-------------------------------------------------------------------//
    //                      HIGH SPEED ESTIMATION                        //
    //-------------------------------------------------------------------//
    // Check if unit timer overflow event happened for high speed calculation
    if(p_qepRegs->QFLG.bit.UTO)
    {
        p_speed->thetaDir       = p_qepRegs->QEPSTS.bit.QDF; //(!(p_qepRegs->QEPSTS.bit.QDF)) ? (-1.0) : (1.0);
        p_speed->theta[NEW]     = p_qepRegs->QPOSLAT / p_enc->thetaMechScaler;
        // Compute angle difference & saturate it between -0.5 and 0.5
//        deltaTheta          = __fsat((speedEst.theta[NEW] - speedEst.theta[OLD] + (float32_t)(p_qepRegs->QFLG.bit.PCO) - (float32_t)(p_qepRegs->QFLG.bit.PCU)), 1.0f, -1.0f) * 0.5f;
        deltaTheta              = p_speed->theta[NEW] - p_speed->theta[OLD] + (float32_t)(p_qepRegs->QFLG.bit.PCO) - (float32_t)(p_qepRegs->QFLG.bit.PCU);
        deltaTheta              = __fsat(deltaTheta, 1.0f, -1.0f);// * 0.5f;
        // Compute high speed estimation
        p_speed->speedHigh      = deltaTheta * p_speed->speedHighScaler;
        // Save last angle
        p_speed->theta[OLD]     = p_speed->theta[NEW];
        // Clear UTO flag
        p_qepRegs->QCLR.all     = EQEP_INT_UNIT_TIME_OUT | EQEP_INT_OVERFLOW | EQEP_INT_UNDERFLOW;
//        // Read latched angle normalized between 0 and 1
//        speedEst.pos[NEW] = p_qepRegs->QPOSLAT / p_enc->mechPosNorm;
//        // Compute angle difference
//        deltaPos = speedEst.pos[NEW] - speedEst.pos[OLD];
//        // Saturate it between -0.5 and 0.5
//        deltaPos += (deltaPos > 0.5) ? (-1.0) : ((deltaPos < -0.5) ? (1.0) : (0.0));
//        // Compute high speed estimation
//        speedEst.highSpeed = deltaPos * speedEst.highSpeedNorm;
//        // Save last angle
//        speedEst.pos[OLD] = speedEst.pos[NEW];
//        // Clear UTO flag
//        p_qepRegs->QCLR.all = EQEP_INT_UNIT_TIME_OUT;
    }

    //-------------------------------------------------------------------//
    //                       LOW SPEED ESTIMATION                        //
    //-------------------------------------------------------------------//
    // Check if unit position event occurred for low speed calculation
    if(p_qepRegs->QEPSTS.bit.UPEVNT)
    {
        // Check if capture value is not valid (direction change and timer overflow)
        bool qepStatus          = (p_qepRegs->QEPSTS.all & (EQEP_STS_CAP_OVRFLW_ERROR | EQEP_STS_CAP_DIR_ERROR));
        // Compute low speed estimation, set sign according QDF
        // Speed is very close to zero because direction changed or the rotor doesn't move fast enough
        p_speed->speedLow       = (qepStatus) ? (0.0) : (((!(p_qepRegs->QEPSTS.bit.QDF)) ? (-1.0) : (1.0)) * p_speed->speedLowScaler / p_qepRegs->QCPRDLAT);
        // Clear position event, direction change and timer overflow flags (even if direction and timer overflow are not set)
        p_qepRegs->QEPSTS.all   = EQEP_STS_UNIT_POS_EVNT | EQEP_STS_CAP_OVRFLW_ERROR | EQEP_STS_CAP_DIR_ERROR;
    }

    //-------------------------------------------------------------------//
    //                     SPEED ESTIMATION MERGE                        //
    //-------------------------------------------------------------------//
    /*
     *
     *
     *                  Merge coefficient shape:
     * low speed     ________
     *                      |\
     *                        \
     *                      |  \
     *                          \
     *                      |    \________      w1 = 70.8 rad/s
     * high speed                |              w2 = 90.7 rad/s
     *                      w1   w2
     *
     *  High speed estimation is used for this decision because this estimation can only be lower
     */

    // Compute merge coefficient // TODO as no merge is computed alpha term is not necessary
//    speedEst.alpha = FMINMAX((0.05f * (FM_ABS(speedEst.highSpeed) - SPEED_ESTIMATION_THRESHOLD)), 1.0f, 0.0f);//    speedEst.alpha = __fmin(__fmax(0.05f * (FM_ABS(speedEst.highSpeed) - SPEED_ESTIMATION_THRESHOLD), 0.0f), 1.0f);
    // Compute speed reference // TODO merge high & low speed - CSDT
    // see : http://www.diegm.uniud.it/petrella/Azionamenti%20Elettrici%20II/Tesine/Petrella%20et%20al.%20-%20Speed%20Measurement%20Algorithms%20for%20Low-Resolution%20Incremental%20Encoder%20Equipped%20Drives_a%20Comparative%20Analysis.pdf
    p_speed->speedRef           = p_speed->speedHigh;//    p_enc->speedEst.speedRef = (1.0f - p_enc->speedEst.alpha) * p_enc->speedEst.lowMechSpeedEst + p_enc->speedEst.alpha * p_enc->speedEst.highMechSpeedEst;
    // Update speeds
    UOMODRI_SPEED_FLT(p_speed->lpf, p_speed->speedMech, p_speed->speedRef);
    p_speed->speedElec          = p_enc->polePairs * p_speed->speedMech;

    //-------------------------------------------------------------------//
    //                        ANGLES COMPUTATION                         //
    //-------------------------------------------------------------------//
    // Update turnNb
    deltaTheta                  = p_enc->thetaMech[NEW] - p_enc->thetaMech[OLD];
    // If angle difference is high enough, we overflowed or underflowed
    p_enc->turnNb              += (deltaTheta > 0.5f) ? (-1.0f) : ((deltaTheta < -0.5f) ? (1.0f) : (0.0f));
    // Saturate turnNb between -128 and 127
    p_enc->turnNb               = (p_enc->turnNb > 127) ? (-128) : ((p_enc->turnNb < -128) ? (127) : (p_enc->turnNb));
    p_enc->rollOverFlag         = ((p_enc->turnNb == 127) || (p_enc->turnNb == -128)) ? (true) : (false);
    // Compute indexed angle
    p_enc->indexedThetaMech     = p_enc->thetaMech[NEW] - p_enc->indexTheta;
    p_enc->indexedThetaMech    += (p_enc->indexedThetaMech < 0.0f) ? (1.0f) : (0.0f);
    // Compute new absolute angle
    p_enc->thetaAbsolute        = ((p_enc->indexCompensated) ? (p_enc->indexedThetaMech) : (p_enc->thetaMech[NEW])) + (float32_t)p_enc->turnNb;

    //-------------------------------------------------------------------//
    //                          INDEX HANDLING                           //
    //-------------------------------------------------------------------//

    // Check if index have been detected
    p_enc->indexDetected        = p_qepRegs->QEPSTS.bit.FIMF;
    // Check if index has been detected
    if (p_qepRegs->QFLG.all & EQEP_INT_INDEX_EVNT_LATCH)
    {
        // Save index position
        p_enc->indexTheta       = p_enc->thetaMechScaler * p_qepRegs->QPOSILAT;
        // Toggle index
        p_enc->indexToggle      = !p_enc->indexToggle;
        // Clear flag
        p_qepRegs->QCLR.all     = EQEP_INT_INDEX_EVNT_LATCH;
    }
}

